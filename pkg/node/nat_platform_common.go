// natLog is the shared logger for every platform's NAT implementation. It lives
// here rather than in a platform file so the Windows and macOS implementations
// log under the same name the Linux one always has.
var natLog = logger.New("NFTables")

// pfAnchor is the pf anchor name this node owns on macOS. It lives here, rather
// than in the darwin file, so the anchor-name handling stays testable off macOS.
// pf keeps anchors in a namespace separate from the main ruleset, so the name
// only has to be unique on the host.
const pfAnchor = "com.p2ptap.nat"

// ExitNATParams is everything a platform NAT implementation needs. Linux reads
// only the interface names (it matches by iifname and lets the kernel pick the
// source address), while Windows and macOS both need the TAP network itself:
// WinNat keys on an internal prefix, and a pf nat rule needs a source network.
type ExitNATParams struct {
	WANInterface string
	TapName      string
	TapIPv4      string // CIDR as configured, e.g. "10.0.0.1/24"
	TapIPv6      string // CIDR as configured, e.g. "fd00::1/64"
	MSS          int
}

// natUnsupportedError is the message a build without a NAT backend returns.
// It names the platform and the consequence, because the alternative — a silent
// success — is precisely the bug this exists to prevent: the node reported
// itself as a working Exit Node and forwarded nothing at all.
func natUnsupportedError(goos, role, consequence string) error {
	return fmt.Errorf("%s NAT is not available on %s: this build has no NAT implementation, so %s. Run that node on Linux, Windows or macOS", role, goos, consequence)
}

// firstLine returns the first non-empty line of command output. PowerShell and
// most CLI tools put the actionable error text there, and a full backtrace in
// the node log is worse than useless to an operator.
func firstLine(out string) string {
	for _, line := range strings.Split(out, "\n") {
		if s := strings.TrimSpace(line); s != "" {
			return s
		}
	}
	return ""
}

// natPrefixV4 canonicalises a configured TAP address into the network prefix
// that NAT rules must match: "10.0.0.1/24" -> "10.0.0.0/24". Platforms that
// key NAT on the source network (WinNat, pf) reject a host address, and
// silently doing nothing there is exactly the failure mode this file exists to
// avoid, so an unusable value returns ok=false.
func natPrefixV4(cidr string) (string, bool) {
	cidr = strings.TrimSpace(cidr)
	if cidr == "" {
		return "", false
	}
	ip, ipnet, err := net.ParseCIDR(cidr)
	if err != nil {
		return "", false
	}
	if ip.To4() == nil {
		return "", false
	}
	ones, bits := ipnet.Mask.Size()
	if bits != 32 || ones < 0 {
		return "", false
	}
	return fmt.Sprintf("%s/%d", ipnet.IP.String(), ones), true
}

// natPrefixV6 is the IPv6 twin of natPrefixV4.
func natPrefixV6(cidr string) (string, bool) {
	cidr = strings.TrimSpace(cidr)
	if cidr == "" {
		return "", false
	}
	ip, ipnet, err := net.ParseCIDR(cidr)
	if err != nil {
		return "", false
	}
	if ip.To4() != nil || ip.To16() == nil {
		return "", false
	}
	ones, bits := ipnet.Mask.Size()
	if bits != 128 || ones < 0 {
		return "", false
	}
	return fmt.Sprintf("%s/%d", ipnet.IP.String(), ones), true
}

// natIPv6GapReason explains why a configured IPv6 TAP network will not be
// masqueraded. It exists because the subnet-router path used to take only the
// IPv4 network: an operator with tap_ipv6 set got a working IPv4 exit and a
// silently dead IPv6 one, with nothing in the log to say so.
//
// It returns "" when there is nothing to report: no IPv6 network is configured
// (the common IPv4-only deployment) or the backend covers it.
//
// It never returns an error the caller must act on, and callers must not turn it
// into one: a NAT backend without IPv6 has to leave IPv4 forwarding untouched.
// Failing the whole setup here would take a fully working IPv4 exit node down
// over a secondary family.
func natIPv6GapReason(role, backend string, backendHasIPv6 bool, tapIPv6 string) string {
	tapIPv6 = strings.TrimSpace(tapIPv6)
	if tapIPv6 == "" {
		return ""
	}
	if !backendHasIPv6 {
		return fmt.Sprintf("%s IPv6 NAT is not supported by %s, so tap_ipv6=%q is ignored and client IPv6 traffic through this node will be dropped; IPv4 forwarding is unaffected", role, backend, tapIPv6)
	}
	if _, ok := natPrefixV6(tapIPv6); !ok {
		return fmt.Sprintf("%s NAT on %s will not masquerade IPv6: tap_ipv6=%q is not an IPv6 network in CIDR form, so IPv6 traffic through this node will be dropped; IPv4 forwarding is unaffected", role, backend, tapIPv6)
	}
	return ""
}

// powerShellQuote wraps s in single quotes for PowerShell, doubling embedded
// single quotes. Every value passed through here is generated by this package,
// but the escaping keeps a hostile interface name from ever becoming a second
// statement.
func powerShellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}

// pfNatAnchor builds the pf rules that masquerade tunnel traffic on macOS.
// wanIface must be a concrete interface: pf has no "the default route" token,
// so an unresolved value yields no rules and the caller must fail loudly
// rather than install an anchor that matches nothing.
//
// Only NAT rules belong here. pf tags each anchor with a type and rejects rules
// of the wrong kind inside it, so an MSS clamp (a "scrub" rule) would have to
// live in a separate scrub-anchor. macOS therefore gets NAT without an MSS
// clamp; the client side falls back to PMTU discovery.
func pfNatAnchor(wanIface, tapV4, tapV6 string) []string {
	wanIface = strings.TrimSpace(wanIface)
	if wanIface == "" || wanIface == "auto" {
		return nil
	}
	var rules []string
	if p4, ok := natPrefixV4(tapV4); ok {
		rules = append(rules,
			fmt.Sprintf("nat on %s inet from %s to any -> (%s)", wanIface, p4, wanIface))
	}
	if p6, ok := natPrefixV6(tapV6); ok {
		rules = append(rules,
			fmt.Sprintf("nat on %s inet6 from %s to any -> (%s)", wanIface, p6, wanIface))
	}
	return rules
}

// pfConfHasAnchor reports whether pf.conf loads our anchor as a nat-anchor.
// This check is what separates "rules loaded" from "rules actually evaluated":
// pf silently ignores an anchor the main ruleset never references, and it also
// silently ignores NAT rules placed in a plain `anchor` instead of a
// `nat-anchor`.
func pfConfHasAnchor(conf, anchor string) bool {
	for _, line := range strings.Split(conf, "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if !strings.HasPrefix(line, "nat-anchor") {
			continue
		}
		if strings.Contains(line, `"`+anchor+`"`) {
			return true
		}
	}
	return false
}

// pfConfWithAnchor returns pf.conf with our nat-anchor loaded, or the input
// unchanged when it already is. The line goes first so any later host rule
// cannot shadow ours, and so the anchor is declared before the anchoring
// section ends.
func pfConfWithAnchor(conf, anchor string) string {
	if pfConfHasAnchor(conf, anchor) {
		return conf
	}
	if conf != "" && !strings.HasSuffix(conf, "\n") {
		conf += "\n"
	}
	return "nat-anchor \"" + anchor + "\"\n" + conf
}
