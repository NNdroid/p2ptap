        let currentLang = localStorage.getItem('p2ptap_boot_lang') || (navigator.language.startsWith('zh') ? (navigator.language.includes('TW') || navigator.language.includes('HK') ? 'zh-TW' : 'zh-CN') : (i18n[navigator.language.split('-')[0]] ? navigator.language.split('-')[0] : 'en'));
        if (!i18n[currentLang]) currentLang = 'zh-CN';

        function t(k) {
            return (i18n[currentLang] && i18n[currentLang][k]) || (i18n['zh-CN'] && i18n['zh-CN'][k]) || (i18n['en'] && i18n['en'][k]) || k;
        }

        function changeLanguage(lang) {
            if (!i18n[lang]) return;
            currentLang = lang;
            localStorage.setItem('p2ptap_boot_lang', lang);
            document.getElementById('langSelect').value = lang;
            applyStaticI18n();
            renderDashboard();
            renderLogs();
        }

        function applyStaticI18n() {
            document.querySelectorAll('[data-i18n]').forEach(el => {
                const k = el.getAttribute('data-i18n');
                if (k) el.innerText = t(k);
            });
            document.querySelectorAll('[data-i18n-ph]').forEach(el => {
                const k = el.getAttribute('data-i18n-ph');
                if (k) el.placeholder = t(k);
            });
            document.querySelectorAll('[data-i18n-title]').forEach(el => {
                const k = el.getAttribute('data-i18n-title');
                if (k) el.title = t(k);
            });
        }
